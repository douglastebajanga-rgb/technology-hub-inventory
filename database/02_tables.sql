-- Role-based User Management
CREATE TABLE app_users (
    user_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR2(50) NOT NULL UNIQUE,
    password_hash VARCHAR2(255) NOT NULL,
    role VARCHAR2(20) CHECK (role IN ('ADMIN', 'MANAGER', 'STAFF')),
    status VARCHAR2(20) DEFAULT 'ACTIVE',
    last_login TIMESTAMP
);

-- Categories
CREATE TABLE categories (
    category_id NUMBER DEFAULT seq_categories_id.NEXTVAL PRIMARY KEY,
    category_name VARCHAR2(100) NOT NULL UNIQUE,
    description VARCHAR2(255)
);

-- Suppliers
CREATE TABLE suppliers (
    supplier_id NUMBER DEFAULT seq_suppliers_id.NEXTVAL PRIMARY KEY,
    supplier_name VARCHAR2(150) NOT NULL,
    contact_name VARCHAR2(100),
    phone VARCHAR2(30),
    email VARCHAR2(100)
);

-- Products
CREATE TABLE products (
    product_id NUMBER DEFAULT seq_products_id.NEXTVAL PRIMARY KEY,
    product_name VARCHAR2(150) NOT NULL,
    category_id NUMBER REFERENCES categories(category_id),
    supplier_id NUMBER REFERENCES suppliers(supplier_id),
    unit_price NUMBER(10, 2) NOT NULL,
    stock_quantity NUMBER DEFAULT 0 NOT NULL,
    reorder_level NUMBER DEFAULT 5
);

-- Customers
CREATE TABLE customers (
    customer_id NUMBER DEFAULT seq_customers_id.NEXTVAL PRIMARY KEY,
    customer_name VARCHAR2(150) NOT NULL,
    phone VARCHAR2(30),
    email VARCHAR2(100)
);

-- Sales
CREATE TABLE sales (
    sale_id NUMBER DEFAULT seq_sales_id.NEXTVAL PRIMARY KEY,
    customer_id NUMBER REFERENCES customers(customer_id),
    sale_date TIMESTAMP DEFAULT SYSTIMESTAMP,
    total_amount NUMBER(12, 2) NOT NULL
);

-- Sale Items
CREATE TABLE sale_items (
    sale_item_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id NUMBER REFERENCES sales(sale_id) ON DELETE CASCADE,
    product_id NUMBER REFERENCES products(product_id),
    quantity NUMBER NOT NULL,
    unit_price NUMBER(10, 2) NOT NULL,
    subtotal NUMBER(12, 2) NOT NULL
);

-- Inventory Transactions
CREATE TABLE inventory_transactions (
    transaction_id NUMBER DEFAULT seq_transactions_id.NEXTVAL PRIMARY KEY,
    product_id NUMBER REFERENCES products(product_id),
    transaction_type VARCHAR2(20) CHECK (transaction_type IN ('IN', 'OUT', 'ADJUSTMENT')),
    quantity NUMBER NOT NULL,
    transaction_date TIMESTAMP DEFAULT SYSTIMESTAMP,
    notes VARCHAR2(255)
);

-- Audit Log
CREATE TABLE audit_log (
    audit_id NUMBER DEFAULT seq_audit_id.NEXTVAL PRIMARY KEY,
    action_date TIMESTAMP DEFAULT SYSTIMESTAMP,
    username VARCHAR2(50),
    action_type VARCHAR2(20),
    table_name VARCHAR2(50),
    record_id NUMBER
);